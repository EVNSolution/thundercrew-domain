package com.thundercrew.opsapi.bike.domain;

/**
 * 차량의 용도. 260804 미팅 요구사항 — "차량에 용도(배송용/클린차량) 추가".
 *
 * <p><b>배차 방식과 다른 축이다.</b> 용도는 이 차량이 무슨 일에 쓰이는지이고,
 * 배차 방식(계약의 {@code serviceType})은 그 일을 어떻게 배정하는지다. 두 축은
 * 직교한다 — 배송용 차량을 콜로도 순차로도 배차할 수 있다.
 *
 * <p>이 둘이 한 컬럼에 겹쳐 있던 이력이 있다. V25 가 {@code bikes.service_type} 에
 * 용도(DELIVERY/CLEANING)를 넣었고, V36 이 같은 컬럼의 값을 배차 방식으로
 * 재브랜드하면서 용도 정보가 사라졌다. V51 이 용도를 차량으로 되돌린다.
 *
 * <p>용도는 자주 바뀌지 않는다("자주 안 바꿀 거임" — 미팅 원문). 지금은 어떤 로직도
 * 이 값으로 분기하지 않는 서술 값이므로 자유롭게 편집할 수 있다. 용도별 화면 분리나
 * 주문 풀 모델이 들어오면 진행 중 배차가 있는 차량의 변경을 막아야 한다.
 */
public enum BikePurpose {
    /** 배송용. 함체를 달고 배송 주문을 처리한다. */
    DELIVERY,
    /** 클린차량. 세차·클리닝 서비스에 쓴다. */
    CLEANING
}
