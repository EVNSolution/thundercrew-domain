-- 주기 값: 엑셀이 "7,000~10,000km 또는 10~12개월" 같은 범위라 cycle_km /
-- cycle_months 에는 **하한**을 넣는다 — 임박 알림이 이르게 뜨는 쪽이 놓치는
-- 쪽보다 안전하다. 원문 범위·비고는 memo 에 보존한다.

